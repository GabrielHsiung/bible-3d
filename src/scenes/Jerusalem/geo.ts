export function inPoly(x: number, z: number, poly: P[]) {
  let inside = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, zi] = poly[i]
    const [xj, zj] = poly[j]
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) inside = !inside
  }
  return inside
}

/** 梯形內的雙線性插值點：u 由西到東、v 由北到南（0–1） */
export function quadPoint(q: P[], u: number, v: number): P {
  const [nw, ne, se, sw] = q
  const nx = nw[0] + (ne[0] - nw[0]) * u
  const nz = nw[1] + (ne[1] - nw[1]) * u
  const sx = sw[0] + (se[0] - sw[0]) * u
  const sz = sw[1] + (se[1] - sw[1]) * u
  return [nx + (sx - nx) * v, nz + (sz - nz) * v]
}
